def row_of(title, code):
    for node in FLAT:
        if node["code"] == code:
            return node[f"row_{title}"]
    raise KeyError((title, code))


def source_sum(sheet, codes, col):
    parts = ",".join(f"'{sheet}'!{col}{row_of(sheet, code)}" for code in codes)
    return f"=SUM({parts})"


def worst_risk(sheet, codes):
    high = ",".join(f"'{sheet}'!L{row_of(sheet, code)}=\"Высокий\"" for code in codes)
    mid = ",".join(f"'{sheet}'!L{row_of(sheet, code)}=\"Средний\"" for code in codes)
    return f'=IF(OR({high}),"Высокий",IF(OR({mid}),"Средний",IF(COUNTA({",".join(f"\'{sheet}\'!L{row_of(sheet, code)}" for code in codes)})=0,"","Низкий")))'


