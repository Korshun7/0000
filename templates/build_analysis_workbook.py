def walk(nodes, depth=0, parent_id=None):
    flat = []
    for node in nodes:
        item = {
            "code": node["code"],
            "name": node["name"],
            "depth": depth,
            "parent_id": parent_id,
            "is_leaf": "children" not in node,
        }
        if item["is_leaf"]:
            item.update({k: node[k] for k in ("b0", "b1", "f1", "f2", "f3", "reason", "risk", "comment", "klass")})
        flat.append(item)
        if "children" in node:
            flat.extend(walk(node["children"], depth + 1, node["code"]))
    return flat


FLAT = walk(TREE)


def assert_example():
    leaves = [n for n in FLAT if n["is_leaf"]]
    for n in leaves:
        delta = n["b1"] - n["b0"]
        factors = n["f1"] + n["f2"] + n["f3"]
        if delta != factors:
            raise SystemExit(f"Тождество нарушено у {n['code']}: Δ={delta}, факторы={factors}")
    by_code = {n["code"]: n for n in FLAT if n["is_leaf"]}

    def s(codes, field):
        return sum(by_code[c][field] for c in codes)

    groups = {
        "01": ["01.01", "01.02", "01.03", "01.04"],
        "02": ["02.01", "02.02", "02.03", "02.04", "02.05"],
        "03.01": ["03.01.01", "03.01.02", "03.01.03", "03.01.04", "03.01.05", "03.01.06", "03.01.07"],
        "03.02": ["03.02.01", "03.02.02", "03.02.03", "03.02.04", "03.02.05"],
        "03.03": ["03.03.01", "03.03.02", "03.03.03", "03.03.04", "03.03.05"],
        "04": ["04.01", "04.02", "04.03"],
        "05": ["05.01", "05.02", "05.03"],
        "06": ["06.01", "06.02", "06.03"],
    }
    expected = {
        "01": (320, 380, 25, 28, 7),
        "02": (280, 340, 18, 35, 7),
        "03.01": (3100, 3600, 280, 190, 30),
        "03.02": (1400, 1620, 110, 95, 15),
        "03.03": (700, 860, 55, 70, 35),
        "04": (480, 590, 30, 25, 55),
        "05": (220, 250, 12, 0, 18),
        "06": (520, 535, 5, 3, 7),
    }
    for code, (b0, b1, f1, f2, f3) in expected.items():
        got = tuple(s(groups[code], f) for f in ("b0", "b1", "f1", "f2", "f3"))
        if got != (b0, b1, f1, f2, f3):
            raise SystemExit(f"Группа {code}: ожидалось {(b0, b1, f1, f2, f3)}, получено {got}")
    total = tuple(sum(n[f] for n in leaves) for f in ("b0", "b1", "f1", "f2", "f3"))
    if total != (7020, 8175, 535, 446, 174):
        raise SystemExit(f"Итог примера не сошелся: {total}")
    if total[2] + total[3] + total[4] != total[1] - total[0]:
        raise SystemExit("Итоговое тождество факторов не сошлось")
    risk_total = sum(RISK_SUM.get(n["code"], 0) for n in leaves)
    if risk_total != 444:
        raise SystemExit(f"Сумма риска примера не сошлась: {risk_total}")


